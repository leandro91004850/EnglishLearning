        : (now ?? DateTime.now()).toUtc();
    final title = _text(x['title']), author = _text(x['author']);
    rows.add({
      'id': vid,
      'source': choices.contains(x['source']) ? x['source'] : 'auto',
      'at': when,
      'pos': _num(x['pos']),
      'dur': _num(x['dur']),
      'title': title.isEmpty ? null : title,
      'author': author.isEmpty ? null : author,
    });
  }
  return rows;
}

Future<List<List<Object?>>> _insertMany(
  DbSession s,
  String sql,
  List<List<Object?>> rows, {
  bool returning = false,
}) async {
  final out = <List<Object?>>[];
  for (var i = 0; i < rows.length; i += batchRows) {
    final part = rows.sublist(i, math.min(i + batchRows, rows.length));
    final width = part.first.length;
    final values = [for (var r = 0; r < part.length; r++) '(${_marks(width, start: r * width + 1)})'].join(', ');
    final result = await s.query(sql.replaceFirst('{}', values), [for (final row in part) ...row]);
    if (returning) out.addAll(result);
  }
  return out;
}

/// Conexão com o PostgreSQL, uma operação de cada vez.
///
/// Leituras ([run]) esperam a resposta; gravações vão para uma fila ([submit])
/// e rodam na ordem em que chegaram, sem fazer a interface ou a tradução
/// esperar. Se o servidor não responde, as operações devolvem o padrão pedido,
/// o motivo fica em [error] e só se tenta conectar de novo depois de
/// [retryAfter].
class Banco {
  Banco(Map<String, String>? config, {DbConnector? connect, DateTime Function()? now, this.mobile = false})
    : config = Map.of(config ?? const {}),
      _connector = connect,
      _now = now ?? DateTime.now;

  Map<String, String> config;
  final DbConnector? _connector; // os testes trocam o PostgreSQL por outro conector
  final DateTime Function() _now;

  /// No celular as mensagens de "sem conexão" ganham uma dica sobre localhost.
  final bool mobile;

  DbConnection? _conn;
  Future<DbConnection>? _connecting;
  DateTime _nextTry = _epoch;
  final _Mutex _mutex = _Mutex();

  /// Muda quando os dados de acesso mudam: ids de outro banco não valem.
  int generation = 0;

  /// Problema com o banco ("" = tudo certo, ou ainda não tentou).
  String error = '';

  /// Chamado com o novo [error] quando ele muda.
  void Function(String error)? onStatus;

  Future<void> _tail = Future.value();
  int _pending = 0;

  factory Banco.fromEnv(File file, {bool mobile = false}) => Banco(readEnv(file), mobile: mobile);

  bool get configured =>
      _connector != null || ['DB_HOST', 'DB_NAME', 'DB_USER'].any((k) => (config[k] ?? '').isNotEmpty);

  /// Conectado agora.
  bool get connected => _conn?.isOpen ?? false;

  DbParams params() => DbParams(config);

  String describe() => _connector != null ? 'banco de teste' : params().describe();

  String friendly(Object e) => friendlyDbError(toDbFailure(e), params(), mobile: mobile, ios: mobile && Platform.isIOS);

  // ---- conexão ----

  Future<DbConnection?> _connection({required bool wait}) async {
    final current = _conn;
    if (current != null) {
      if (current.isOpen) return current;
      _conn = null; // o servidor fechou a conexão
    }
    if (!wait || !configured || _now().isBefore(_nextTry)) return null;
    final pending = _connecting;
    if (pending != null) {
      try {
        return await pending;
      } catch (_) {
        return null;
      }
    }
    final gen = generation;
    final attempt = _open(gen);
    _connecting = attempt;
    try {
      final conn = await attempt;
      if (gen != generation) {
        await _quiet(conn.close); // os dados de acesso mudaram enquanto conectava
        return null;
      }
      _conn = conn;
      Log.info('Banco de dados conectado: ${describe()}');
      return conn;
    } catch (e) {
      if (gen == generation) {
        _nextTry = _now().add(retryAfter);
        _setError(friendly(e), e);
      }
      return null;
    } finally {
      if (identical(_connecting, attempt)) _connecting = null;
    }
  }

  Future<DbConnection> _open(int gen) async {
    final connector = _connector;
    final conn = connector != null ? await connector() : await PgDb.open(params());
    try {
      await conn.transaction((s) async {
        for (final statement in schema) {
          await s.query(statement);
        }
      });
    } catch (_) {
      await _quiet(conn.close);
      rethrow;
    }
    return conn;
  }

  static Future<void> _quiet(Future<void> Function() fn) async {
    try {
      await fn();
    } catch (_) {
      // nada a fazer
    }
  }

  void _setError(String message, [Object? e]) {
    if (message == error) return;
    error = message;
    if (message.isNotEmpty) Log.warning('Banco de dados (${describe()}): $message${e == null ? '' : ' [$e]'}');
    final listener = onStatus;
    if (listener != null) scheduleMicrotask(() => listener(error));
  }

  /// Roda [fn] numa transação e devolve o que ela devolver; sem banco, [fallback].
  /// `wait: false`: só usa a conexão se ela já estiver aberta.
  Future<T> run<T>(String what, Future<T> Function(DbSession s) fn, T fallback, {bool wait = true}) async {
    final conn = await _connection(wait: wait);
    if (conn == null) return fallback;
    return _mutex.protect(() async {
      if (!identical(_conn, conn)) return fallback; // outra operação perdeu a conexão
      try {
        final result = await conn.transaction(fn);
        _setError('');
        return result;
      } catch (e) {
        final failure = toDbFailure(e);
        if (failure.network || !conn.isOpen) {
          _conn = null;
          unawaited(_quiet(conn.close));
          _nextTry = _now().add(retryAfter);
          _setError(friendly(failure), failure);
        } else {
          Log.warning('Banco de dados: erro em $what: $failure');
          _setError('Erro no banco de dados: ${_firstLine(failure.message)}', failure);
        }
        return fallback;
      }
    });
  }

  // ---- fila de gravações ----

  /// Põe uma gravação na fila e volta na hora. Devolve false se não há banco configurado.
  bool submit(Future<void> Function() fn) {
    if (!configured) return false;
    _pending++;
    _tail = _tail.then((_) async {
      try {
        await fn();
      } catch (e) {
        Log.warning('Banco de dados: falha ao gravar: $e');
      } finally {
        _pending--;
      }
    });
    return true;
  }

  int get pending => _pending;

  /// Espera a fila de gravações esvaziar. False se o tempo acabou antes.
  Future<bool> flush([Duration timeout = const Duration(seconds: 10)]) async {
    try {
      await _tail.timeout(timeout);
      return true;
    } on TimeoutException {
      return false;
    }
  }

  Future<void> close() async {
    final conn = _conn;
    _conn = null;
    if (conn != null) await _quiet(conn.close);
  }

  /// Passa a usar outros dados de acesso: fecha a conexão atual, e a próxima
  /// operação conecta com os dados novos, sem esperar o intervalo depois de uma
  /// falha. Gravações pendentes que usam ids do banco anterior deixam de valer.
  Future<void> reconfigure(Map<String, String> newConfig) async {
    final old = _conn;
    _conn = null;
    config = Map.of(newConfig);
    generation++;
    _nextTry = _epoch;
    if (old != null) await _quiet(old.close);
    _setError('');
  }

  // ---- vídeos recentes e preferências ----

  /// Lista de recentes, na ordem da tela, no formato do historico.json; null se
  /// o banco não respondeu.
  Future<List<Map<String, Object?>>?> loadRecent() => run<List<Map<String, Object?>>?>('loadRecent', (s) async {
    final rows = await s.query(
      'SELECT r.video_id, r.escolha, r.aberto_em, r.parou_em, r.duracao, '
      'v.titulo, v.autor FROM recentes r JOIN videos v ON v.id = r.video_id ORDER BY r.ordem',
    );
    return [
      for (final r in rows)
        {
          'id': r[0],
          'url': watchUrl(r[0] as String),
          'source': r[1],
          'at': (r[2] as DateTime).millisecondsSinceEpoch ~/ 1000,
          if (r[5] != null) 'title': r[5],
          if (r[6] != null) 'author': r[6],
          if (r[3] != null) 'pos': (r[3] as num).toDouble(),
          if (r[4] != null) 'dur': (r[4] as num).toDouble(),
        },
    ];
  }, null);

  /// Troca a lista do banco por [items]; devolve quantos vídeos gravou.
  Future<int> _writeRecent(DbSession s, List<Map<String, Object?>> items) async {
    final rows = recentRows(items, now: _now());
    if (rows.isNotEmpty) {
      // título novo grava; vídeo que já estava igual no banco não é regravado
      await _insertMany(
        s,
        'INSERT INTO videos (id, url, titulo, autor) VALUES {} ON CONFLICT (id) DO UPDATE '
        'SET titulo = COALESCE(EXCLUDED.titulo, videos.titulo), autor = COALESCE(EXCLUDED.autor, videos.autor) '
        'WHERE (EXCLUDED.titulo IS NOT NULL AND EXCLUDED.titulo IS DISTINCT FROM videos.titulo) '
        'OR (EXCLUDED.autor IS NOT NULL AND EXCLUDED.autor IS DISTINCT FROM videos.autor)',
        [
          for (final r in rows) [r['id'], watchUrl(r['id']! as String), r['title'], r['author']],
        ],
      );
    }
    await s.query('DELETE FROM recentes');
    if (rows.isNotEmpty) {
      await _insertMany(s, 'INSERT INTO recentes (video_id, ordem, escolha, aberto_em, parou_em, duracao) VALUES {}', [
        for (var n = 0; n < rows.length; n++)
          [rows[n]['id'], n, rows[n]['source'], rows[n]['at'], rows[n]['pos'], rows[n]['dur']],
      ]);
    }
    return rows.length;
  }

  /// Grava a lista inteira numa transação: a ordem do banco é a da tela.
  Future<bool> saveRecent(List<Map<String, Object?>> items) =>
      run('saveRecent', (s) async => await _writeRecent(s, items) >= 0, false);

  /// Grava só onde estes vídeos pararam e o título deles, sem mexer na lista: é o
  /// que muda a cada poucos segundos enquanto um vídeo toca, e não vale regravar a
  /// lista inteira (ela tem todos os vídeos do banco).
  Future<bool> updateRecent(List<Map<String, Object?>> items) async {
    final rows = recentRows(items, now: _now());
    if (rows.isEmpty) return true;
    return run('updateRecent', (s) async {
      for (final r in rows) {
        await s.query(r'UPDATE recentes SET parou_em = $1, duracao = $2 WHERE video_id = $3', [
          r['pos'],
          r['dur'],
          r['id'],
        ]);
        if (r['title'] != null || r['author'] != null) {
          await s.query(r'UPDATE videos SET titulo = COALESCE($1, titulo), autor = COALESCE($2, autor) WHERE id = $3', [
            r['title'],
            r['author'],
            r['id'],
          ]);
        }
      }
      return true;
    }, false);
  }

  /// A lista tem todos os vídeos do banco: os que não estão nela (cortados pelo
  /// limite de 30 de uma versão antiga, ou tirados com × no app Python) entram no
  /// fim, os mais novos primeiro. Devolve quantos entraram.
  Future<int> addMissingVideos() => run('addMissingVideos', (s) async {
    // ON CONFLICT: outro app pode estar fazendo o mesmo agora
    final added = await s.query(
      'INSERT INTO recentes (video_id, ordem, escolha, aberto_em) '
      "SELECT v.id, m.ultima + ROW_NUMBER() OVER (ORDER BY v.criado_em DESC, v.id), 'auto', v.criado_em "
      'FROM videos v, (SELECT COALESCE(MAX(ordem), -1) AS ultima FROM recentes) m '
      'WHERE NOT EXISTS (SELECT 1 FROM recentes r WHERE r.video_id = v.id) '
      'ON CONFLICT (video_id) DO NOTHING RETURNING video_id',
    );
    if (added.isNotEmpty) Log.info('Banco de dados: ${added.length} vídeos que estavam fora da lista entraram nela');
    return added.length;
  }, 0);

  Future<Map<String, Object?>?> loadPrefs() => run<Map<String, Object?>?>('loadPrefs', (s) async {
    final out = <String, Object?>{};
    for (final r in await s.query('SELECT chave, valor FROM preferencias')) {
      try {
        out[r[0] as String] = jsonDecode(r[1] as String);
      } on FormatException {
        // valor estragado: fica de fora
      }
    }
    return out;
  }, null);

  Future<bool> savePref(String key, Object value) => run('savePref', (s) async {
    await s.query(_upsertPref, [key, jsonEncode(value)]);
    return true;
  }, false);

  // ---- legendas, traduções e palavras ----

  Future<SavedTrack?> _loadTrack(DbSession s, String where, List<Object?> params) async {
    final head = await s.query(
      'SELECT l.id, l.codigo, l.nome_idioma, l.gerada, l.idioma_traducao FROM legendas l $where',
      params,
    );
    if (head.isEmpty) return null;
    final row = head.first;
    final id = row[0] as int, code = row[1] as String, generated = row[3] as bool, target = row[4] as String;
    final name = row[2] as String?;
    final rows = await s.query(
      r'SELECT inicio, duracao, texto, traducao FROM frases WHERE legenda_id = $1 ORDER BY ordem',
      [id],
    );
    if (rows.isEmpty) return null;
    return SavedTrack(
      id: id,
      db: generation,
      meta: SubtitleMeta(
        cues: [for (final r in rows) Cue((r[0] as num).toDouble(), (r[1] as num).toDouble(), r[2] as String)],
        sourceName: name == null || name.isEmpty ? code : name,
        sourceCode: code,
        generated: generated,
        target: target,
        targetName: targetName(target),
      ),
      translations: [
        for (var i = 0; i < rows.length; i++)
          if (rows[i][3] != null) (i, rows[i][3] as String),
      ],
    );
  }

  /// A legenda que esta opção do seletor de idioma já abriu neste vídeo, com as
  /// traduções já feitas.
  Future<SavedTrack?> findTranscript(String vid, String choice, {bool wait = true}) => run<SavedTrack?>(
    'findTranscript',
    (s) => _loadTrack(
      s,
      r'JOIN legendas_escolhidas e ON e.legenda_id = l.id WHERE e.video_id = $1 AND e.escolha = $2',
      [vid, choice],
    ),
    null,
    wait: wait,
  );

  /// A mesma coisa, procurando pela faixa (outra opção do seletor pode ter aberto a mesma).
  Future<SavedTrack?> findTrack(String vid, String code, bool generated, {bool wait = true}) => run<SavedTrack?>(
    'findTrack',
    (s) => _loadTrack(s, r'WHERE l.video_id = $1 AND l.codigo = $2 AND l.gerada = $3', [vid, code, generated]),
    null,
    wait: wait,
  );

  /// Lembra que esta opção do seletor de idioma abriu a faixa [saved].
  Future<bool> linkChoice(String vid, String choice, SavedTrack saved) => run('linkChoice', (s) async {
    if (saved.db != generation || saved.id == null) return false; // faixa de um banco que já foi trocado
    await s.query(_upsertChoice, [vid, choice, saved.id]);
    return true;
  }, false);

  /// Grava a faixa de legenda, as falas (ainda sem tradução) e as palavras de
  /// cada fala. O id da faixa vai para `saved.id`, para as traduções que chegarem
  /// depois saberem onde gravar.
  Future<void> saveTranscript(SavedTrack saved, String vid, String choice) async {
    final meta = saved.meta;
    final lang = langFamily(meta.sourceCode);
    saved.id = await run<int?>('saveTranscript', (s) async {
      saved.db = generation;
      await s.query(r'INSERT INTO videos (id, url) VALUES ($1, $2) ON CONFLICT (id) DO NOTHING', [vid, watchUrl(vid)]);
      final inserted = await s.query(
        r'INSERT INTO legendas (video_id, codigo, idioma, nome_idioma, gerada, idioma_traducao) '
        r'VALUES ($1, $2, $3, $4, $5, $6) ON CONFLICT (video_id, codigo, gerada) '
        r'DO UPDATE SET nome_idioma = EXCLUDED.nome_idioma RETURNING id',
        [vid, meta.sourceCode, lang, meta.sourceName, meta.generated, meta.target],
      );
      final trackId = inserted.first.first as int;
      await s.query(_upsertChoice, [vid, choice, trackId]);
      final count = await s.query(r'SELECT COUNT(*) FROM frases WHERE legenda_id = $1', [trackId]);
      if ((count.first.first as int) == 0) {
        final cues = meta.cues;
        final ids = await _insertMany(
          s,
          'INSERT INTO frases (legenda_id, ordem, inicio, duracao, texto) VALUES {} RETURNING id, ordem',
          [
            for (var i = 0; i < cues.length; i++) [trackId, i, cues[i].start, cues[i].dur, _text(cues[i].text)],
          ],
          returning: true,
        );
        final byOrder = {for (final r in ids) r[1] as int: r[0] as int};
        await _saveWords(s, lang, [
          for (var i = 0; i < cues.length; i++)
            if (byOrder[i] != null) (byOrder[i]!, false, splitWords(cues[i].text)),
        ]);
      }
      return trackId;
    }, null);
  }

  /// Grava as traduções que chegaram e as palavras de cada uma. Não faz nada se
  /// a faixa não chegou a ser gravada (banco fora do ar).
  Future<void> saveTranslations(SavedTrack saved, List<(int, String)> pairs) async {
    final trackId = saved.id;
    if (trackId == null || pairs.isEmpty) return;
    final lang = langFamily(saved.meta.target);
    await run('saveTranslations', (s) async {
      if (saved.db != generation) return false; // faixa de um banco que já foi trocado
      final byOrder = <int, int>{};
      for (var i = 0; i < pairs.length; i += batchRows) {
        final part = pairs.sublist(i, math.min(i + batchRows, pairs.length));
        final cases = [for (var k = 0; k < part.length; k++) 'WHEN \$${2 * k + 1} THEN \$${2 * k + 2}'].join(' ');
        final trackParam = 2 * part.length + 1;
        await s.query(
          'UPDATE frases SET traducao = CASE ordem $cases END '
          'WHERE legenda_id = \$$trackParam AND ordem IN (${_marks(part.length, start: trackParam + 1)})',
          [
            for (final (order, text) in part) ...[order, _text(text)],
            trackId,
            for (final (order, _) in part) order,
          ],
        );
        final rows = await s.query(
          'SELECT ordem, id FROM frases WHERE legenda_id = \$1 AND ordem IN (${_marks(part.length, start: 2)})',
          [trackId, for (final (order, _) in part) order],
        );
        for (final r in rows) {
          byOrder[r[0] as int] = r[1] as int;
        }
      }
      if (byOrder.isEmpty) return false;
      final fids = byOrder.values.toList();
      for (var i = 0; i < fids.length; i += batchRows) {
        // tradução refeita: as palavras velhas saem
        final part = fids.sublist(i, math.min(i + batchRows, fids.length));
        await s.query(
          'DELETE FROM frases_palavras WHERE da_traducao = \$1 AND frase_id IN (${_marks(part.length, start: 2)})',
          [true, ...part],
        );
      }
      await _saveWords(s, lang, [
        for (final (order, text) in pairs)
          if (byOrder[order] != null) (byOrder[order]!, true, splitWords(text)),
      ]);
      return true;
    }, false);
  }

  /// Grava as palavras que ainda não existem e a posição de cada palavra em cada frase.
  Future<void> _saveWords(DbSession s, String lang, List<(int, bool, List<String>)> entries) async {
    final vocab = {for (final (_, _, words) in entries) ...words}.toList()..sort();
    if (vocab.isEmpty) return;
    await _insertMany(s, 'INSERT INTO palavras (idioma, palavra) VALUES {} ON CONFLICT (idioma, palavra) DO NOTHING', [
      for (final w in vocab) [lang, w],
    ]);
    final ids = <String, int>{};
    for (var i = 0; i < vocab.length; i += batchRows) {
      final part = vocab.sublist(i, math.min(i + batchRows, vocab.length));
      final rows = await s.query(
        'SELECT palavra, id FROM palavras WHERE idioma = \$1 AND palavra IN (${_marks(part.length, start: 2)})',
        [lang, ...part],
      );
      for (final r in rows) {
        ids[r[0] as String] = r[1] as int;
      }
    }
    final links = [
      for (final (fid, translated, words) in entries)
        for (var n = 0; n < words.length; n++)
          if (ids[words[n]] != null) [fid, translated, n, ids[words[n]]],
    ];
    if (links.isEmpty) return;
    await _insertMany(
      s,
      'INSERT INTO frases_palavras (frase_id, da_traducao, posicao, palavra_id) VALUES {} ON CONFLICT DO NOTHING',
      links,
    );
  }

  /// Leva para o banco uma legenda já traduzida que só estava no aparelho (cache
  /// local), sem duplicar o que já está lá.
  Future<void> storeComplete(String vid, String choice, SubtitleMeta meta, List<(int, String)> pairs) async {
    var saved = await findTranscript(vid, choice) ?? await findTrack(vid, meta.sourceCode, meta.generated);
    if (saved == null) {
      saved = SavedTrack(meta: meta);
      await saveTranscript(saved, vid, choice);
    } else {
      // outra legenda com as mesmas falas? (os índices das traduções precisam casar)
      if (saved.meta.cues.length != meta.cues.length) return;
      await linkChoice(vid, choice, saved);
    }
    final have = {for (final (i, _) in saved.translations) i};
    await saveTranslations(saved, [
      for (final p in pairs)
        if (!have.contains(p.$1)) p,
    ]);
  }

  // ---- diagnóstico ----

  /// Conecta, cria as tabelas se faltarem e conta o que já está guardado.
  Future<(bool, String)> check() async {
    if (!configured) return (false, notConfigured);
    final counts = await run<Map<String, int>?>('check', (s) async {
      final out = <String, int>{};
      for (final table in ['videos', 'legendas', 'frases', 'palavras']) {
        out[table] = (await s.query('SELECT COUNT(*) FROM $table')).first.first as int;
      }
      return out;
    }, null);
    if (counts == null) return (false, error);
    return (
      true,
      '${describe()}, com ${thousands(counts['videos']!)} vídeos, ${thousands(counts['legendas']!)} legendas, '
          '${thousands(counts['frases']!)} falas e ${thousands(counts['palavras']!)} palavras guardadas',
    );
  }
}
