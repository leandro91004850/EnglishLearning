/// Pares CHAVE=valor do arquivo .env. Linhas começadas por # são comentário;
/// aspas em volta do valor são tiradas. Arquivo que não existe: {}.
Map<String, String> readEnv(File file) {
  String text;
  try {
    text = file.readAsStringSync();
  } on FileSystemException {
    return {};
  }
  if (text.startsWith('﻿')) text = text.substring(1);
  final data = <String, String>{};
  for (var line in const LineSplitter().convert(text)) {
    line = line.trim();
    if (line.isEmpty || line.startsWith('#') || !line.contains('=')) continue;
    final eq = line.indexOf('=');
    var key = line.substring(0, eq).trim();
    var value = line.substring(eq + 1).trim();
    if (key.startsWith('export ')) key = key.substring(7).trim();
    if (value.length >= 2 && value[0] == value[value.length - 1] && (value[0] == '"' || value[0] == "'")) {
      value = value.substring(1, value.length - 1);
    }
    data[key] = value;
  }
  return data;
}

String? _envKey(String line) {
  final t = line.trim();
  if (t.isEmpty || t.startsWith('#') || !t.contains('=')) return null;
  final key = t.substring(0, t.indexOf('=')).trim();
  return key.startsWith('export ') ? key.substring(7).trim() : key;
}

/// Valor como o [readEnv] lê de volta: entre aspas se tem espaço nas pontas ou aspas em volta.
String _envValue(String value) {
  final quoted = value.length >= 2 && value[0] == value[value.length - 1] && (value[0] == '"' || value[0] == "'");
  return value != value.trim() || quoted ? '"$value"' : value;
}

/// Grava os dados de acesso no .env: troca as linhas DB_* e mantém o resto
/// (comentários), escrevendo num temporário e trocando.
void writeEnv(File file, Map<String, String> config) {
  List<String> lines;
  try {
    var text = file.readAsStringSync();
    if (text.startsWith('﻿')) text = text.substring(1);
    lines = const LineSplitter().convert(text);
  } on FileSystemException {
    lines = const LineSplitter().convert(envHeader);
  }
  bool wanted(String key) => (config[key] ?? '').isNotEmpty || key == 'DB_PASSWORD';
  final out = <String>[];
  final written = <String>{};
  for (final line in lines) {
    final key = _envKey(line);
    if (key == null || !envKeys.contains(key)) {
      out.add(line);
    } else if (!written.contains(key) && wanted(key)) {
      out.add('$key=${_envValue(config[key] ?? '')}');
      written.add(key);
    }
  }
  for (final key in envKeys) {
    if (!written.contains(key) && wanted(key)) out.add('$key=${_envValue(config[key] ?? '')}');
  }
  file.parent.createSync(recursive: true);
  final tmp = File('${file.path}.tmp');
  tmp.writeAsStringSync('${out.join('\n')}\n', flush: true);
  tmp.renameSync(file.path);
}

/// Dados de acesso vindos da tela de configuração -> chaves do .env, ou
/// ({}, motivo do erro). Senha em branco mantém a que já estava salva.
(Map<String, String>, String) configFromForm(Map<String, Object?> form, Map<String, String> current) {
  String field(String k) => (form[k] ?? '').toString().trim();
  final host = field('host'), portText = field('port'), dbname = field('dbname');
  final user = field('user'), sslmode = field('sslmode');
  final typed = form['password'];
  final password = typed == null || typed == '' ? current['DB_PASSWORD'] ?? '' : typed.toString();
  final bad = RegExp('[\r\n\u0000]');
  if ([host, portText, dbname, user, sslmode, password].any(bad.hasMatch)) {
    return (const {}, 'Os campos não podem ter quebra de linha.');
  }
  final port = portText.isEmpty ? '5432' : portText;
  if (host.isEmpty) return (const {}, 'Informe o servidor (ex.: localhost).');
  final portNumber = RegExp(r'^[0-9]+$').hasMatch(port) ? int.parse(port) : 0;
  if (portNumber <= 0 || portNumber >= 65536) {
    return (const {}, 'A porta precisa ser um número de 1 a 65535 (a do PostgreSQL costuma ser 5432).');
  }
  if (dbname.isEmpty) return (const {}, 'Informe o nome do banco (ex.: legendas_yt).');
  if (user.isEmpty) return (const {}, 'Informe o usuário (ex.: postgres).');
  if (!sslModes.contains(sslmode)) return (const {}, 'Modo de conexão segura (SSL) inválido.');
  return (
    {
      'DB_HOST': host,
      'DB_PORT': '$portNumber',
      'DB_NAME': dbname,
      'DB_USER': user,
      'DB_PASSWORD': password,
      if (sslmode.isNotEmpty) 'DB_SSLMODE': sslmode,
    },
    '',
  );
}

