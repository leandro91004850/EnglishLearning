/// Uma transação aberta (os testes trocam o PostgreSQL por outra implementação).
abstract interface class DbSession {
  /// Roda o SQL com parâmetros posicionais ($1, $2...) e devolve as linhas.
  Future<List<List<Object?>>> query(String sql, [List<Object?> params]);
}

abstract interface class DbConnection {
  bool get isOpen;
  Future<T> transaction<T>(Future<T> Function(DbSession session) fn);
  Future<void> close();
}

typedef DbConnector = Future<DbConnection> Function();

/// O PostgreSQL de verdade (pacote `postgres`).
abstract final class PgDb {
  static Future<DbConnection> open(DbParams p) async {
    try {
      final conn = await _openDatabase(p);
      try {
        await conn.execute('SET statement_timeout = $statementTimeoutMs');
      } catch (_) {
        await conn.close();
        rethrow;
      }
      return _PgConnection(conn);
    } catch (e) {
      throw toDbFailure(e);
    }
  }

  static Future<pg.Connection> _attempt(DbParams p, String database, pg.SslMode mode) => pg.Connection.open(
    pg.Endpoint(host: p.host, port: p.port, database: database, username: p.user, password: p.password),
    settings: pg.ConnectionSettings(
      sslMode: mode,
      connectTimeout: connectTimeout,
      queryTimeout: const Duration(milliseconds: statementTimeoutMs + 5000),
      applicationName: 'Legendas YT',
    ),
  );

  /// O modo SSL do .env, como o libpq: "" (padrão) e "prefer" tentam com SSL e,
  /// se o servidor não tiver, sem; "allow" tenta sem e, se o servidor exigir, com.
  static Future<pg.Connection> _openWithSsl(DbParams p, String database) async {
    switch (p.sslmode) {
      case 'disable':
        return _attempt(p, database, pg.SslMode.disable);
      case 'require':
        return _attempt(p, database, pg.SslMode.require);
      case 'verify-ca' || 'verify-full':
        return _attempt(p, database, pg.SslMode.verifyFull);
      case 'allow':
        try {
          return await _attempt(p, database, pg.SslMode.disable);
        } on pg.ServerException catch (e) {
          if (e.code == '28000') return _attempt(p, database, pg.SslMode.require);
          rethrow;
        }
      default:
        try {
          return await _attempt(p, database, pg.SslMode.require);
        } on pg.PgException catch (e) {
          if (e.message.contains('does not support SSL')) return _attempt(p, database, pg.SslMode.disable);
          rethrow;
        }
    }
  }

  static Future<pg.Connection> _openDatabase(DbParams p) async {
    try {
      return await _openWithSsl(p, p.database);
    } on pg.ServerException catch (e) {
      if (e.code != '3D000') rethrow;
      // o banco ainda não existe: cria (se o usuário puder) conectando ao banco padrão
      final pg.Connection admin;
      try {
        admin = await _openWithSsl(p, 'postgres');
      } catch (_) {
        throw e;
      }
      try {
        final name = '"${p.database.replaceAll('"', '""')}"';
        try {
          await admin.execute("CREATE DATABASE $name ENCODING 'UTF8' TEMPLATE template0");
        } on pg.ServerException {
          await admin.execute('CREATE DATABASE $name');
        }
        Log.info('Banco de dados ${p.database} criado');
      } on pg.ServerException catch (e2) {
        Log.warning('Não consegui criar o banco ${p.database}: ${e2.message}');
        throw e;
      } finally {
        await admin.close();
      }
      return _openWithSsl(p, p.database);
    }
  }
}

class _PgConnection implements DbConnection {
  _PgConnection(this._conn);
  final pg.Connection _conn;

  @override
  bool get isOpen => _conn.isOpen;

  @override
  Future<T> transaction<T>(Future<T> Function(DbSession session) fn) async {
    try {
      return await _conn.runTx((tx) => fn(_PgSession(tx)));
    } catch (e) {
      throw toDbFailure(e);
    }
  }

  @override
  Future<void> close() => _conn.close();
}

class _PgSession implements DbSession {
  _PgSession(this._session);
  final pg.Session _session;

  @override
  Future<List<List<Object?>>> query(String sql, [List<Object?> params = const []]) async {
    final result = await _session.execute(sql, parameters: params.isEmpty ? null : params);
    return [for (final row in result) List<Object?>.of(row)];
  }
}

/// Uma operação de cada vez na conexão.
class _Mutex {
  Future<void> _last = Future.value();

  Future<T> protect<T>(Future<T> Function() fn) {
    final previous = _last;
    final done = Completer<void>();
    _last = done.future;
    return previous.then((_) => fn()).whenComplete(done.complete);
  }
}

