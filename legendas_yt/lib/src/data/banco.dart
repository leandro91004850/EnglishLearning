/// Falha do banco num formato que não depende do driver (os testes criam estas).
class DbFailure implements Exception {
  const DbFailure(
    this.message, {
    this.code,
    this.network = false,
    this.osError,
    this.sslUnsupported = false,
    this.badCertificate = false,
  });

  final String message;

  /// Código do PostgreSQL (SQLSTATE), ex. 28P01 senha errada, 3D000 banco não existe.
  final String? code;

  /// Sem resposta do servidor (recusou, tempo esgotado, rede).
  final bool network;
  final int? osError;
  final bool sslUnsupported;
  final bool badCertificate;

  @override
  String toString() => code == null ? message : '$message [$code]';
}

/// Converte o erro do driver ou da rede em [DbFailure].
DbFailure toDbFailure(Object e) {
  if (e is DbFailure) return e;
  if (e is pg.BadCertificateException) return DbFailure(e.message, badCertificate: true);
  if (e is pg.ServerException) return DbFailure(e.message, code: e.code);
  if (e is pg.PgException) {
    if (e.message.contains('does not support SSL')) return DbFailure(e.message, sslUnsupported: true);
    return DbFailure(e.message, network: true); // o driver perdeu a conexão
  }
  if (e is SocketException) return DbFailure(e.toString(), network: true, osError: e.osError?.errorCode);
  if (e is TimeoutException) return DbFailure('tempo esgotado', network: true);
  if (e is HandshakeException || e is TlsException) return DbFailure(e.toString(), badCertificate: true);
  return DbFailure(e.toString());
}

String _firstLine(String text) {
  final t = text.trim();
  return t.isEmpty ? 'erro desconhecido' : t.split('\n').first;
}

/// Mensagem para a interface sobre uma falha ao conectar (o `_friendly` do banco.py).
String friendlyDbError(DbFailure f, DbParams p, {bool mobile = false, bool ios = false}) {
  final low = f.message.toLowerCase();
  switch (f.code) {
    case '28P01':
      return 'O PostgreSQL recusou o usuário ou a senha: confira os dois.$notSaving';
    case '28000':
      if (low.contains('pg_hba.conf')) {
        return 'O servidor PostgreSQL não aceita conexões deste aparelho (pg_hba.conf): '
            'libere o endereço dele no servidor.$notSaving';
      }
      return 'O PostgreSQL recusou o usuário ou a senha: confira os dois.$notSaving';
    case '3D000':
      return 'O banco "${p.database}" não existe no servidor e não consegui criá-lo: crie com '
          'CREATE DATABASE ${p.database};$notSaving';
    case '42501':
      return 'O usuário ${p.user} não tem permissão para criar as tabelas no banco ${p.database}: '
          'use o dono do banco ou dê a permissão.$notSaving';
  }
  if (f.sslUnsupported) {
    return 'O servidor não aceita conexão segura (SSL): escolha "Padrão" ou "Desligada".$notSaving';
  }
  if (f.badCertificate) {
    return 'A conexão segura (SSL) com o servidor falhou: o certificado não foi aceito.$notSaving';
  }
  if (f.network) {
    final local = p.host == 'localhost' || p.host == '127.0.0.1' || p.host == '::1';
    final hint = mobile && local
        ? ' No celular, "localhost" é o próprio celular: use o endereço (IP) do computador onde '
              'está o PostgreSQL.'
        : ios && f.osError == 65
        ? ' No iPhone, confira em Ajustes › Privacidade e Segurança › Rede Local se o Legendas YT '
              'tem permissão.'
        : '';
    return 'Sem conexão com o PostgreSQL em ${p.host}:${p.port}: o servidor está ligado? '
        'Confira o servidor e a porta.$hint$notSaving';
  }
  return 'Erro ao conectar ao banco de dados: ${_firstLine(f.message)}.$notSaving';
}

